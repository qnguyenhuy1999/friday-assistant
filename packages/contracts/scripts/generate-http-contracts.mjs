import { readFile, writeFile } from "node:fs/promises";
import { URL } from "node:url";
import prettier from "prettier";

const source = new URL("../schemas/v1/http/responses.json", import.meta.url);
const target = new URL("../src/wire/http.generated.ts", import.meta.url);
const schema = JSON.parse(await readFile(source, "utf8"));
const type = (node) => {
  if (node.$ref) return node.$ref.split("/").at(-1);
  if (node.enum) return node.enum.map((value) => JSON.stringify(value)).join(" | ");
  if (node.anyOf) return node.anyOf.map(type).join(" | ");
  if (Array.isArray(node.type)) return node.type.map((value) => type({ type: value })).join(" | ");
  if (node.type === "string") return "string";
  if (node.type === "boolean") return "boolean";
  if (node.type === "integer" || node.type === "number") return "number";
  if (node.type === "null") return "null";
  if (node.type === "array") return `Array<${type(node.items)}>`;
  if (node.type === "object") return `{ ${Object.entries(node.properties ?? {}).map(([name, value]) => `${JSON.stringify(name)}: ${type(value)}`).join("; ")} }`;
  return "JsonValue";
};
const declarations = Object.entries(schema.definitions).map(([name, definition]) => {
  const properties = Object.entries(definition.properties ?? {}).map(([property, value]) => `  ${property}: ${type(value)};`).join("\n");
  return `export interface ${name} {\n${properties}\n}`;
}).join("\n\n");
const pages = Object.entries(schema.responses).filter(([name]) => name.endsWith("Page")).map(([name, definition]) => {
  const item = definition.properties.items.items.$ref.split("/").at(-1);
  return `export type ${name[0].toUpperCase()}${name.slice(1)} = Page<${item}>;`;
}).join("\n");
const validators = Object.keys(schema.responses).map((name) => {
  const exportName = `validate${name[0].toUpperCase()}${name.slice(1)}`;
  return `export const ${exportName}: WireValidator = (value, path) => assertWire("${name}", value, path);`;
}).join("\n");
const output = `// Generated by packages/contracts/scripts/generate-http-contracts.mjs. Do not edit.\nimport Ajv from "ajv";\nimport type { JsonValue } from "./json-value";\nimport type { Page } from "./pagination";\n\n${declarations}\n\n${pages}\n\nexport type WireValidator = (value: unknown, path: string) => void;\nexport class WireFormatError extends Error {\n  constructor(readonly path: string, readonly issues: string) {\n    super(\`Response for \${path} does not match the v1 HTTP wire contract: \${issues}\`);\n    this.name = "WireFormatError";\n  }\n}\n\nconst schema = ${JSON.stringify(schema, null, 2)} as Record<string, unknown>;\ndelete schema.$schema; // Ajv's default draft accepts this v1 subset.\nconst ajv = new Ajv({ allErrors: true, strict: false });\najv.addSchema(schema, "v1-http");\nconst validators = Object.fromEntries(Object.keys((schema.responses ?? {}) as Record<string, unknown>).map((name) => [name, ajv.compile({ $ref: \`v1-http#/responses/\${name}\` })]));\nfunction assertWire(name: string, value: unknown, path: string): void {\n  const validate = validators[name];\n  if (!validate) throw new Error(\`Missing wire validator: \${name}\`);\n  if (!validate(value)) throw new WireFormatError(path, ajv.errorsText(validate.errors));\n}\n${validators}\n`;
await writeFile(target, await prettier.format(output, { parser: "typescript" }));
